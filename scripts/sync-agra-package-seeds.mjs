#!/usr/bin/env node
/** Content-only seed: never creates fare_rules, bookings, profiles or payments. */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const packages = JSON.parse(readFileSync(resolve(root, "backend/src/db/agra-packages.seed.json"), "utf8"));
const check = process.argv.includes("--check");
assert.equal(packages.length, 10, "Keep this a focused, reviewed Agra collection.");
assert.equal(new Set(packages.map((pkg) => pkg.packageCode)).size, packages.length);
for (const pkg of packages) {
  assert.equal(pkg.startingPriceInr, null, `${pkg.packageCode}: do not seed a price`);
  assert.deepEqual(pkg.fleetPrices, {}, `${pkg.packageCode}: do not seed vehicle prices`);
  assert.equal(pkg.nightChargeInr, null);
  assert.equal(pkg.source, "Agra");
  assert.ok(pkg.itinerary.length >= 4 && pkg.gallery.length > 0);
}

function emit(path, content) {
  const target = resolve(root, path);
  if (check) {
    assert.equal(readFileSync(target, "utf8"), content, `${path} is out of sync; run npm run packages:sync.`);
  } else {
    writeFileSync(target, content);
  }
}

// Each app remains independently buildable. No frontend import from backend/.
// The snapshot is refreshed by live publishing too, so --check must not demand
// that a legitimate live catalog remain identical to this initial seed.
if (!check) emit("react/src/data/generated-published-tour-packages.json", JSON.stringify(packages.map((pkg) => ({
  ...pkg, slug: pkg.packageCode, image: pkg.imageUrl, upgrades: [],
})), null, 2) + "\n");

const rows = packages.map((pkg) => ({
  id: pkg.id, code: pkg.packageCode, name: pkg.name, duration_text: pkg.durationText,
  days: pkg.days, nights: pkg.nights, source: pkg.source, destination: pkg.destination,
  inclusions_highlight: pkg.inclusionsHighlight, inclusions_note: pkg.inclusionsNote,
  image_url: pkg.imageUrl, gallery: pkg.gallery, inclusions: pkg.inclusions,
  exclusions: pkg.exclusions, itinerary: pkg.itinerary, status: pkg.status,
}));
const payload = JSON.stringify(rows, null, 2);
assert.ok(!payload.includes("$agra_seed$"));
emit("backend/migrations/0057_curated_agra_packages.sql", `-- Generated by scripts/sync-agra-package-seeds.mjs. Research: docs/AGRA_PACKAGE_RESEARCH.md
-- Content only. Pricing lives in fare_rules; deliberately do not insert any fares.
-- Additive and idempotent: operator-managed rows with the same code are untouched.
-- Existing bookings, prices, unrelated packages and customer records are never changed.
INSERT INTO public.tour_packages (
  id, code, name, duration_text, days, nights, source, destination,
  inclusions_highlight, inclusions_note, image_url, gallery,
  inclusions, exclusions, itinerary, status
)
SELECT id, code, name, duration_text, days, nights, source, destination,
       inclusions_highlight, inclusions_note, image_url, gallery,
       inclusions, exclusions, itinerary, status
FROM jsonb_to_recordset($agra_seed$${payload}$agra_seed$::jsonb) AS seed (
  id uuid, code text, name text, duration_text text, days integer, nights integer,
  source text, destination text, inclusions_highlight text, inclusions_note text,
  image_url text, gallery jsonb, inclusions jsonb, exclusions jsonb, itinerary jsonb, status text
)
ON CONFLICT (code) DO NOTHING;
`);
console.log(check
  ? `Checked ${packages.length} unpriced Agra seed invariants and content-only SQL (live snapshot is independent).`
  : `Synced ${packages.length} unpriced Agra package seeds, offline snapshot and content-only SQL.`);
